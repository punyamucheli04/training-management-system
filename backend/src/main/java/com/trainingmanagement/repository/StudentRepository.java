package com.trainingmanagement.repository;

import com.trainingmanagement.model.Student;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.jdbc.core.RowMapper;
import org.springframework.jdbc.support.GeneratedKeyHolder;
import org.springframework.jdbc.support.KeyHolder;
import org.springframework.stereotype.Repository;

import java.sql.PreparedStatement;
import java.sql.Statement;
import java.util.List;
import java.util.Optional;

/**
 * Data access for the student table.
 *
 * Reads come from the VIEW student_department_view (student JOIN department)
 * and call the STORED FUNCTION calculate_attendance_percentage() for every row.
 * Writes go to the base table student.
 */
@Repository
public class StudentRepository {

    private static final String SELECT_STUDENTS = """
            SELECT v.Student_ID, v.Name, v.Gender, v.DOB, v.Email, v.Mobile_Number,
                   v.CGPA, v.Dept_ID, v.Dept_Name, v.HOD_Name,
                   calculate_attendance_percentage(v.Student_ID) AS Attendance_Pct
              FROM student_department_view v
            """;

    private static final RowMapper<Student> ROW_MAPPER = (rs, rowNum) -> {
        Student s = new Student();
        s.setStudentId(rs.getInt("Student_ID"));
        s.setName(rs.getString("Name"));
        s.setGender(rs.getString("Gender"));
        s.setDob(RowUtils.getDate(rs, "DOB"));
        s.setEmail(rs.getString("Email"));
        s.setMobileNumber(rs.getString("Mobile_Number"));
        s.setCgpa(rs.getBigDecimal("CGPA"));
        s.setDeptId(RowUtils.getInteger(rs, "Dept_ID"));
        s.setDeptName(rs.getString("Dept_Name"));
        s.setHodName(rs.getString("HOD_Name"));
        s.setAttendancePct(rs.getBigDecimal("Attendance_Pct"));
        return s;
    };

    private final JdbcTemplate jdbcTemplate;

    public StudentRepository(JdbcTemplate jdbcTemplate) {
        this.jdbcTemplate = jdbcTemplate;
    }

    /**
     * All students, optionally filtered by a search text that is matched
     * with LIKE against name, email, mobile number and department name.
     */
    public List<Student> findAll(String search) {
        if (search == null || search.isBlank()) {
            return jdbcTemplate.query(SELECT_STUDENTS + " ORDER BY v.Student_ID", ROW_MAPPER);
        }
        String like = "%" + search.trim() + "%";
        return jdbcTemplate.query(
                SELECT_STUDENTS
                        + " WHERE v.Name LIKE ? OR v.Email LIKE ? OR v.Mobile_Number LIKE ? OR v.Dept_Name LIKE ?"
                        + " ORDER BY v.Student_ID",
                ROW_MAPPER, like, like, like, like);
    }

    public Optional<Student> findById(int studentId) {
        return jdbcTemplate.query(SELECT_STUDENTS + " WHERE v.Student_ID = ?", ROW_MAPPER, studentId)
                .stream().findFirst();
    }

    public boolean existsById(int studentId) {
        Integer count = jdbcTemplate.queryForObject(
                "SELECT COUNT(*) FROM student WHERE Student_ID = ?", Integer.class, studentId);
        return count != null && count > 0;
    }

    /** True if another student (not excludeId) already uses this email. */
    public boolean emailInUse(String email, Integer excludeId) {
        Integer count = jdbcTemplate.queryForObject(
                "SELECT COUNT(*) FROM student WHERE Email = ? AND Student_ID <> ?",
                Integer.class, email, excludeId == null ? -1 : excludeId);
        return count != null && count > 0;
    }

    /**
     * INSERT and return the AUTO_INCREMENT key generated by MySQL.
     * A KeyHolder collects the key through Statement.RETURN_GENERATED_KEYS.
     */
    public int insert(Student s) {
        String sql = "INSERT INTO student (Name, Gender, DOB, Email, Mobile_Number, CGPA, Dept_ID) "
                + "VALUES (?, ?, ?, ?, ?, ?, ?)";
        KeyHolder keyHolder = new GeneratedKeyHolder();
        jdbcTemplate.update(connection -> {
            PreparedStatement ps = connection.prepareStatement(sql, Statement.RETURN_GENERATED_KEYS);
            ps.setString(1, s.getName());
            ps.setString(2, s.getGender());
            ps.setObject(3, s.getDob());
            ps.setString(4, s.getEmail());
            ps.setString(5, s.getMobileNumber());
            ps.setBigDecimal(6, s.getCgpa());
            ps.setObject(7, s.getDeptId());
            return ps;
        }, keyHolder);
        return keyHolder.getKey().intValue();
    }

    public int update(int studentId, Student s) {
        return jdbcTemplate.update(
                "UPDATE student SET Name = ?, Gender = ?, DOB = ?, Email = ?, Mobile_Number = ?, CGPA = ?, Dept_ID = ? "
                        + "WHERE Student_ID = ?",
                s.getName(), s.getGender(), s.getDob(), s.getEmail(), s.getMobileNumber(),
                s.getCgpa(), s.getDeptId(), studentId);
    }

    public int delete(int studentId) {
        return jdbcTemplate.update("DELETE FROM student WHERE Student_ID = ?", studentId);
    }
}
